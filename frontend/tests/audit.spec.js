import { test, expect } from '@playwright/test'
const event = (id, title = `Event ${id}`) => ({ id, title, description: 'Test event', date: '2030-01-15T18:00:00', application_deadline: null, location: 'Online', url: 'https://example.com/event', source: 'Test', is_active: true, tags: ['hackathon'], scraped_at: '2026-01-01T00:00:00', image_url: null, thumbnail_url: null })
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('eventradar:lang', 'en'))
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    return route.fulfill({ json: path === '/api/events' ? { events: [event(1)], total_pages: 1, total_count: 1 } : path === '/api/sources' ? [] : null })
  })
})
test('later event pages remain searchable', async ({ page }) => {
  await page.route('**/api/events?**', route => {
    const second = new URL(route.request().url()).searchParams.get('page') === '2'
    return route.fulfill({ json: { events: second ? [event(201, 'Later page event')] : Array.from({ length: 200 }, (_, i) => event(i + 1)), total_pages: 2, total_count: 201, page: second ? 2 : 1, page_size: 200 } })
  })
  await page.goto('/')
  await page.locator('.hero-search-input').fill('Later page event')
  await expect(page.locator('.event-card')).toHaveCount(1)
  await expect(page.getByText('Later page event', { exact: true })).toBeVisible()
})
test('every full-catalog page (home, bootcamp guide) fetches all API pages and shares one cache entry', async ({ page }) => {
  const pagesRequested = []
  await page.route('**/api/events?**', route => {
    const n = new URL(route.request().url()).searchParams.get('page') || '1'
    pagesRequested.push(n)
    return route.fulfill({ json: { events: n === '2' ? [event(201, 'Later page event')] : Array.from({ length: 200 }, (_, i) => event(i + 1)), total_pages: 2, total_count: 201, page: Number(n), page_size: 200 } })
  })
  await page.goto('/bootcamp-rehberi')
  await expect.poll(() => pagesRequested.includes('2')).toBe(true)
  await page.locator('a[href="/"]').first().click() // client-side nav keeps the react-query cache
  await page.locator('.hero-search-input').fill('Later page event')
  await expect(page.getByText('Later page event', { exact: true })).toBeVisible()
})
