test('announcement traps focus, closes on Escape and restores focus', async ({ page }) => {
  await page.route('**/api/announcements/latest', route => route.fulfill({ json: { id: 1, title: 'Notice', message: 'Test notice', created_at: '2026-01-01T00:00:00' } }))
  await page.goto('/')
  const search = page.locator('.hero-search-input')
  await search.focus()
  const dialog = page.getByRole('dialog', { name: 'Notice' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button').first()).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button').last()).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button').first()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(search).toBeFocused()
})
