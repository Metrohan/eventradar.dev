test('Tab cycles through the topmost of two dialogs in order', async ({ page }) => {
  await page.route('**/api/announcements/latest', route => route.fulfill({ json: { id: 1, title: 'Notice', message: 'Test notice', created_at: '2026-01-01T00:00:00' } }))
  await page.goto('/')
  await expect(page.getByRole('dialog', { name: 'Notice' })).toBeVisible()
  await page.locator('.support-btn-link').first().evaluate(el => el.click())
  await expect(page.getByRole('dialog')).toHaveCount(2)
  const topDialog = page.getByRole('dialog').last()
  const index = () => topDialog.evaluate(el => [...el.querySelectorAll('button, a[href]')].indexOf(document.activeElement))
  const count = await topDialog.evaluate(el => el.querySelectorAll('button, a[href]').length)
  expect(count).toBeGreaterThan(1)
  expect(await index()).toBe(0)
  // Two competing trap handlers would reset focus to the first element on every Tab.
  for (let i = 1; i <= count + 1; i += 1) {
    await page.keyboard.press('Tab')
    expect(await index()).toBe(i % count)
  }
})
